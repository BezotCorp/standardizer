#!/usr/bin/env bash
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

fail() {
  printf 'Package integrity check failed: %s\n' "$*" >&2
  exit 1
}

MODE="${1:-}"

case "$MODE" in
  "" | --before-generation) ;;
  *) fail "unknown argument: $MODE" ;;
esac

# Check both the index and working tree, including untracked files.
STATUS="$(git status --porcelain=v1 --untracked-files=all)"

if [[ -n "$STATUS" ]]; then
  printf '%s\n' "$STATUS" >&2
  fail "the Git working tree or index contains unexpected changes"
fi

if [[ "$MODE" == "--before-generation" ]]; then
  printf 'Source integrity check passed.\n'
  exit 0
fi

GENERATED_FILES=(
  "data/routing.bin"
  "data/tools.bin"
)

# Generated artifacts must exist, remain untracked and be ignored by Git.
for FILE in "${GENERATED_FILES[@]}"; do
  [[ -f "$FILE" && ! -L "$FILE" && -s "$FILE" ]] ||
    fail "missing or invalid generated artifact: $FILE"

  if git ls-files --error-unmatch -- "$FILE" >/dev/null 2>&1; then
    fail "generated artifact is tracked by Git: $FILE"
  fi

  git check-ignore -q -- "$FILE" ||
    fail "generated artifact is not ignored by Git: $FILE"
done

# Cargo creates these metadata files itself.
# They must not already exist in the source tree.
for FILE in Cargo.toml.orig .cargo_vcs_info.json; do
  if [[ -e "$FILE" || -L "$FILE" ]]; then
    fail "unexpected Cargo metadata file in source tree: $FILE"
  fi
done

# Inspect the actual package contents, including ignored files.
PACKAGE_FILES="$(cargo package --list --locked --allow-dirty)"

while IFS= read -r FILE; do
  [[ -n "$FILE" ]] || continue

  case "$FILE" in
    Cargo.toml.orig | .cargo_vcs_info.json)
      # Metadata generated by Cargo during packaging.
      continue
      ;;
    data/routing.bin | data/tools.bin)
      # Explicitly authorized generated artifacts.
      continue
      ;;
  esac

  git ls-files --error-unmatch -- "$FILE" >/dev/null 2>&1 ||
    fail "unauthorized untracked package file: $FILE"

done <<< "$PACKAGE_FILES"

# Ensure both generated artifacts are actually included.
for FILE in "${GENERATED_FILES[@]}"; do
  grep -Fxq -- "$FILE" <<< "$PACKAGE_FILES" ||
    fail "generated artifact is missing from package: $FILE"
done

# Recheck the repository after inspecting the package.
STATUS="$(git status --porcelain=v1 --untracked-files=all)"

if [[ -n "$STATUS" ]]; then
  printf '%s\n' "$STATUS" >&2
  fail "the repository changed during package validation"
fi

printf 'Package integrity check passed.\n'
printf 'Authorized generated artifacts:\n'
printf '  %s\n' "${GENERATED_FILES[@]}"
